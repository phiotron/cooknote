"""Sinh lib/src/ui/theme/color_tokens.dart từ design/hifi/tokens/bepbook-tokens.json.
Chạy: python tool/gen_theme.py  — đổi token ở mockup thì xuất lại JSON rồi chạy lại.
Sinh: ColorScheme sáng/tối + lớp ThemeExtension CookNoteColors (copyWith/lerp đủ trường).
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
d = json.load(open(root / "design/hifi/tokens/bepbook-tokens.json", encoding="utf8"))["flutter"]
out = root / "lib/src/ui/theme/color_tokens.dart"


def c(hexs):
    return "Color(0xFF%s)" % hexs.lstrip("#").upper()


def scheme(name, mode):
    body = "".join("  %s: %s,\n" % (k, c(v)) for k, v in d["ColorScheme"][mode].items())
    return "final %s = ColorScheme(\n  brightness: Brightness.%s,\n%s);\n\n" % (name, mode, body)


fields = list(d["CookNoteColors"]["light"].keys())
L = ["// GENERATED by tool/gen_theme.py from design/hifi/tokens/bepbook-tokens.json — do not edit by hand.\n",
     "// ignore_for_file: lines_longer_than_80_chars\n",
     "import 'package:flutter/material.dart';\n\n"]
L.append("/// Màu theo ngữ nghĩa ngoài ColorScheme (trạng thái, Chế độ nấu, ảnh thay thế).\n")
L.append("/// Tên lớp giữ `CookNoteColors` cho khớp 1:1 với tokens và mockup (đổi tên app không đổi tên token).\n")
L.append("@immutable\nclass CookNoteColors extends ThemeExtension<CookNoteColors> {\n  const CookNoteColors({\n")
L += ["    required this.%s,\n" % f for f in fields]
L.append("  });\n\n")
L += ["  final Color %s;\n" % f for f in fields]
L.append("\n  /// 8 màu nền ảnh thay thế (thẻ index-card), chọn theo danh mục/ký tự đầu.\n")
L.append("  List<Color> get photoPlaceholders => [\n")
L += ["    photoPlaceholder%d,\n" % i for i in range(1, 9)]
L.append("  ];\n\n  @override\n  CookNoteColors copyWith({\n")
L += ["    Color? %s,\n" % f for f in fields]
L.append("  }) => CookNoteColors(\n")
L += ["    %s: %s ?? this.%s,\n" % (f, f, f) for f in fields]
L.append("  );\n\n  @override\n  CookNoteColors lerp(ThemeExtension<CookNoteColors>? other, double t) {\n")
L.append("    if (other is! CookNoteColors) return this;\n    return CookNoteColors(\n")
L += ["      %s: Color.lerp(%s, other.%s, t)!,\n" % (f, f, f) for f in fields]
L.append("    );\n  }\n}\n\n")
L.append(scheme("bepbookLightScheme", "light"))
L.append(scheme("bepbookDarkScheme", "dark"))
for mode in ("light", "dark"):
    body = "".join("  %s: %s,\n" % (k, c(v)) for k, v in d["CookNoteColors"][mode].items())
    L.append("const cookNoteColors%s = CookNoteColors(\n%s);\n\n" % (mode.capitalize(), body))
out.write_text("".join(L).rstrip() + "\n", encoding="utf8")
print("wrote", out, len(fields), "fields")
